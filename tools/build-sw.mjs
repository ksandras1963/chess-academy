// Writes sw.js, the service worker that lets the web version work offline after the first visit.
// It lists every file the app needs and a version made from their contents, so any change to the
// app or the lessons makes phones fetch the new files. Rebuild after any change:
//
//   node tools/build-sw.mjs
//
// (tools/validate.mjs rebuilds it automatically when the content check passes.)

import { readFile, readdir, writeFile } from "node:fs/promises"
import { createHash } from "node:crypto"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
export const SW_FILE = "sw.js"

// What the app loads in the browser. Docs, licenses and tools are not needed offline.
const DIRS = ["css", "js", "content", "fonts", "icons", "vendor"]
const SKIP = /(^|\/)(LICENSE|OFL\.txt|README|.*\.md$)/

async function walk(dir) {
    const out = []
    for (const e of await readdir(path.join(root, dir), { withFileTypes: true })) {
        const rel = `${dir}/${e.name}`
        if (e.isDirectory()) out.push(...await walk(rel))
        else if (!SKIP.test(rel)) out.push(rel)
    }
    return out
}

export async function buildServiceWorker() {
    const files = ["index.html", "manifest.webmanifest"]
    for (const d of DIRS) files.push(...(await walk(d)).sort())
    const hash = createHash("sha256")
    for (const f of files) hash.update(f).update(await readFile(path.join(root, f)))
    const version = hash.digest("hex").slice(0, 12)

    const sw = `// Offline support for the web version. Generated by tools/build-sw.mjs: don't edit by hand.
const CACHE = "ot-${version}"
const FILES = ${JSON.stringify(["./", ...files], null, 4)}

self.addEventListener("install", event => {
    event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(FILES)).then(() => self.skipWaiting()))
})

self.addEventListener("activate", event => {
    event.waitUntil(caches.keys()
        .then(keys => Promise.all(keys.filter(k => k.startsWith("ot-") && k !== CACHE).map(k => caches.delete(k))))
        .then(() => self.clients.claim()))
})

// Network first, so a new version shows at once when online. The saved copy answers when the
// phone is offline, or when the network takes more than a few seconds.
self.addEventListener("fetch", event => {
    const req = event.request
    if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return
    event.respondWith(answer(req))
})

async function answer(req) {
    const cache = await caches.open(CACHE)
    const network = fetch(req).then(res => {
        if (res.ok && res.type === "basic") cache.put(req, res.clone())
        return res
    })
    const saved = (await cache.match(req, { ignoreSearch: true })) ||
        (req.mode === "navigate" ? await cache.match("./") : undefined)
    if (!saved) return network
    const slow = new Promise(resolve => setTimeout(() => resolve(saved), 3000))
    return Promise.race([network.catch(() => saved), slow])
}
`
    await writeFile(path.join(root, SW_FILE), sw)
    return { file: SW_FILE, files: files.length + 1, version }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const r = await buildServiceWorker()
    console.log(`Built ${r.file}: ${r.files} files, version ${r.version}`)
}
